-- Voz de la Operación: tabla central de reportes de operadores
-- Seguro para volver a ejecutar: no borra ni modifica los reportes existentes.

CREATE TABLE IF NOT EXISTS public.voz_operacion_casos (
    row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id TEXT NOT NULL UNIQUE,
    received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reported_at TIMESTAMPTZ NULL,
    operator_name TEXT NULL,
    area TEXT NULL,
    shift TEXT NULL,
    experience TEXT NULL,
    problem_name TEXT NULL,
    problem_type TEXT NULL,
    signals TEXT NULL,
    production_impact TEXT NULL,
    engineering_status TEXT NULL,
    frequency TEXT NULL,
    situation_narrative TEXT NULL,
    source_schema TEXT NULL,
    record JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_voz_operacion_casos_reported_at
    ON public.voz_operacion_casos (reported_at DESC);
CREATE INDEX IF NOT EXISTS idx_voz_operacion_casos_area
    ON public.voz_operacion_casos (area);
CREATE INDEX IF NOT EXISTS idx_voz_operacion_casos_engineering_status
    ON public.voz_operacion_casos (engineering_status);
CREATE INDEX IF NOT EXISTS idx_voz_operacion_casos_problem_name
    ON public.voz_operacion_casos (problem_name);

